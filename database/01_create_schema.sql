--------------------------------------------------------------------------------
-- CampusReserve | 01_create_schema.sql
-- PURPOSE : DDL for the 13 base tables. Only primary keys, NOT NULL and DEFAULT
--           are declared here; foreign keys, UNIQUE and CHECK constraints are
--           added with ALTER TABLE in 02_constraints_indexes.sql so that the
--           DDL syllabus topics (CREATE / ALTER / DROP) are all exercised.
-- COMPAT  : Oracle Database 19c+ (identity columns need 12c+; IS JSON 12.1.0.2+).
-- NOTE    : CHAR(1) 'Y'/'N' flags are used instead of BOOLEAN because the SQL
--           BOOLEAN type exists only from Oracle 23ai.
--------------------------------------------------------------------------------
SET DEFINE OFF

-- 1. ROLES : authorisation level of a user ------------------------------------
CREATE TABLE roles (
    role_id        NUMBER(3)      NOT NULL,
    role_code      VARCHAR2(20)   NOT NULL,
    role_name      VARCHAR2(60)   NOT NULL,
    can_approve    CHAR(1)        DEFAULT 'N' NOT NULL,
    can_administer CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (role_id)
);

-- 2. DEPARTMENTS : academic schools / administrative units --------------------
CREATE TABLE departments (
    dept_id        NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
    dept_code      VARCHAR2(12)   NOT NULL,
    dept_name      VARCHAR2(120)  NOT NULL,
    CONSTRAINT pk_departments PRIMARY KEY (dept_id)
);

-- 3. USERS : every person who can sign in -------------------------------------
CREATE TABLE users (
    user_id        NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    role_id        NUMBER(3)      NOT NULL,
    dept_id        NUMBER(6)      NOT NULL,
    full_name      VARCHAR2(120)  NOT NULL,
    email          VARCHAR2(160)  NOT NULL,
    reg_no         VARCHAR2(20),               -- students / staff ID, optional
    phone          VARCHAR2(20),
    password_hash  VARCHAR2(100)  NOT NULL,    -- bcrypt hash, never plain text
    is_active      CHAR(1)        DEFAULT 'Y' NOT NULL,
    created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    last_login_at  TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (user_id)
);

-- 4. BUILDINGS -----------------------------------------------------------------
CREATE TABLE buildings (
    building_id    NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
    building_code  VARCHAR2(12)   NOT NULL,
    building_name  VARCHAR2(120)  NOT NULL,
    campus_zone    VARCHAR2(40),
    floors         NUMBER(3)      DEFAULT 1 NOT NULL,
    CONSTRAINT pk_buildings PRIMARY KEY (building_id)
);

-- 5. RESOURCE_CATEGORIES : booking policy is a property of the category -------
CREATE TABLE resource_categories (
    category_id        NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY,
    category_code      VARCHAR2(20)  NOT NULL,
    category_name      VARCHAR2(80)  NOT NULL,
    requires_approval  CHAR(1)       DEFAULT 'Y' NOT NULL,
    max_booking_hours  NUMBER(4,1)   DEFAULT 4 NOT NULL,
    min_notice_hours   NUMBER(4,1)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_resource_categories PRIMARY KEY (category_id)
);

-- 6. RESOURCES : anything bookable (lab, hall, classroom, equipment) ----------
CREATE TABLE resources (
    resource_id      NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    resource_code    VARCHAR2(20)  NOT NULL,
    resource_name    VARCHAR2(120) NOT NULL,
    category_id      NUMBER(6)     NOT NULL,
    building_id      NUMBER(6),                -- NULL for portable equipment pool
    managed_by_dept  NUMBER(6)     NOT NULL,
    floor_no         NUMBER(3),
    room_no          VARCHAR2(20),
    capacity         NUMBER(5)     DEFAULT 0 NOT NULL,
    status           VARCHAR2(12)  DEFAULT 'AVAILABLE' NOT NULL,
    opens_at_hour    NUMBER(2)     DEFAULT 8  NOT NULL,
    closes_at_hour   NUMBER(2)     DEFAULT 20 NOT NULL,
    description      VARCHAR2(1000),
    features_json    VARCHAR2(2000),           -- e.g. {"projector":true,"seats":60}
    created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_resources PRIMARY KEY (resource_id)
);

-- 7. BOOKINGS : one reservation of one resource for one time interval ---------
CREATE TABLE bookings (
    booking_id     NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY,
    resource_id    NUMBER(10)     NOT NULL,
    requested_by   NUMBER(10)     NOT NULL,
    title          VARCHAR2(150)  NOT NULL,
    purpose        VARCHAR2(1000),
    attendees      NUMBER(5)      DEFAULT 1 NOT NULL,
    start_time     TIMESTAMP      NOT NULL,
    end_time       TIMESTAMP      NOT NULL,
    status         VARCHAR2(12)   DEFAULT 'PENDING' NOT NULL,
    request_key    VARCHAR2(64),               -- idempotency key from the client
    created_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    cancelled_at   TIMESTAMP,
    cancel_reason  VARCHAR2(400),
    CONSTRAINT pk_bookings PRIMARY KEY (booking_id)
);

-- 8. BOOKING_APPROVALS : the human decision on a booking ----------------------
CREATE TABLE booking_approvals (
    approval_id    NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY,
    booking_id     NUMBER(12)     NOT NULL,
    approver_id    NUMBER(10)     NOT NULL,
    decision       VARCHAR2(10)   NOT NULL,
    remarks        VARCHAR2(500),
    decided_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_booking_approvals PRIMARY KEY (approval_id)
);

-- 9. MAINTENANCE_REQUESTS ------------------------------------------------------
CREATE TABLE maintenance_requests (
    request_id       NUMBER(12)    GENERATED BY DEFAULT AS IDENTITY,
    resource_id      NUMBER(10)    NOT NULL,
    reported_by      NUMBER(10)    NOT NULL,
    assigned_to      NUMBER(10),
    title            VARCHAR2(150) NOT NULL,
    description      VARCHAR2(2000),
    priority         VARCHAR2(10)  DEFAULT 'MEDIUM' NOT NULL,
    status           VARCHAR2(12)  DEFAULT 'OPEN' NOT NULL,
    blocks_booking   CHAR(1)       DEFAULT 'N' NOT NULL,
    created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_at      TIMESTAMP,
    resolution_notes VARCHAR2(1000),
    CONSTRAINT pk_maintenance_requests PRIMARY KEY (request_id)
);

-- 10. RESOURCE_BLACKOUTS : scheduled unavailability (exams, holidays, servicing)
CREATE TABLE resource_blackouts (
    blackout_id      NUMBER(12)    GENERATED BY DEFAULT AS IDENTITY,
    resource_id      NUMBER(10)    NOT NULL,
    start_time       TIMESTAMP     NOT NULL,
    end_time         TIMESTAMP     NOT NULL,
    blackout_type    VARCHAR2(12)  DEFAULT 'MAINTENANCE' NOT NULL,
    reason           VARCHAR2(400) NOT NULL,
    maintenance_id   NUMBER(12),
    created_by       NUMBER(10)    NOT NULL,
    created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_resource_blackouts PRIMARY KEY (blackout_id)
);

-- 11. AUDIT_LOGS : append-only change history written only by triggers -------
CREATE TABLE audit_logs (
    audit_id       NUMBER(14)     GENERATED BY DEFAULT AS IDENTITY,
    table_name     VARCHAR2(40)   NOT NULL,
    record_id      NUMBER(14)     NOT NULL,
    action         VARCHAR2(10)   NOT NULL,
    old_status     VARCHAR2(12),
    new_status     VARCHAR2(12),
    changed_by     NUMBER(10),
    changed_at     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    details        VARCHAR2(1000),
    CONSTRAINT pk_audit_logs PRIMARY KEY (audit_id)
);

-- 12. NOTIFICATIONS ------------------------------------------------------------
CREATE TABLE notifications (
    notification_id NUMBER(14)    GENERATED BY DEFAULT AS IDENTITY,
    user_id         NUMBER(10)    NOT NULL,
    notif_type      VARCHAR2(20)  NOT NULL,
    title           VARCHAR2(150) NOT NULL,
    message         VARCHAR2(500) NOT NULL,
    booking_id      NUMBER(12),
    is_read         CHAR(1)       DEFAULT 'N' NOT NULL,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_notifications PRIMARY KEY (notification_id)
);

-- 13. UTILISATION_SNAPSHOTS : periodic analytics output of a cursor procedure -
CREATE TABLE utilisation_snapshots (
    snapshot_id      NUMBER(12)   GENERATED BY DEFAULT AS IDENTITY,
    resource_id      NUMBER(10)   NOT NULL,
    period_start     DATE         NOT NULL,
    period_end       DATE         NOT NULL,
    booked_hours     NUMBER(8,2)  NOT NULL,
    available_hours  NUMBER(8,2)  NOT NULL,
    utilisation_pct  NUMBER(5,2)  NOT NULL,
    booking_count    NUMBER(6)    NOT NULL,
    generated_at     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_utilisation_snapshots PRIMARY KEY (snapshot_id)
);

-- DDL demonstration: ALTER TABLE ... ADD / MODIFY on an existing table --------
ALTER TABLE users ADD (avatar_initials VARCHAR2(3));
ALTER TABLE users MODIFY (phone VARCHAR2(16));
-- The column was only a demonstration of DROP COLUMN; remove it again.
ALTER TABLE users DROP COLUMN avatar_initials;
